"""
Track Dataset for JAMB Policy
Loads data from a flattened HDF5 file (generated by scripts/generate_training_data.py)
Supports EEF poses and 3D track targets instead of Point Map Prediction.
"""
import sys, os
import h5py

current_file_path = os.path.abspath(__file__)
parent_directory = os.path.dirname(current_file_path)
sys.path.append(os.path.join(parent_directory, '..'))
sys.path.append(os.path.join(parent_directory, '../..'))

from typing import Dict
import torch
import numpy as np
import copy
from jamb_policy.common.pytorch_util import dict_apply
from jamb_policy.common.replay_buffer import ReplayBuffer
from jamb_policy.common.sampler import (
    SequenceSampler,
    get_val_mask,
    downsample_mask,
)
from jamb_policy.model.common.normalizer import (
    LinearNormalizer,
    SingleFieldLinearNormalizer,
)
from jamb_policy.dataset.base_dataset import BaseDataset


class TrackDataset(BaseDataset):
    """
    Dataset for JAMB using Track Prediction
    Loads data directly from a flat HDF5 file containing:
    - action [T, 16] (EEF pose)
    - robot_state [T, 16] (EEF pose)
    - pi3_feature [T, N_patches, 1024]
    - 3d_track [T, N_patches, H_action, 3]
    - track_valid_mask [T, N_patches, H_action]
    - episode_ends [num_episodes]
    """

    def __init__(
        self,
        data_path,
        horizon=1,
        pad_before=0,
        pad_after=0,
        seed=42,
        val_ratio=0.0,
        max_train_episodes=None,
        task_name=None,
        use_dino_features=False,
        use_pi3_features=True,  # requires pi3_features in the tracks zarr/HDF5
        aux_task="track",  # "track": 3D displacement regression;
                           # "pmp": predict future pi3 features (chunk end)
        track_key="3d_track",         # zarr/HDF5 key for track data; use
        mask_key="track_valid_mask",  # "gt_3d_track"/"track_valid_mask_gt"
                                      # for simulator-exact GT tracks
    ):
        super().__init__()
        assert aux_task in ("track", "pmp"), aux_task
        self.task_name = task_name
        self.use_dino_features = use_dino_features
        self.use_pi3_features = use_pi3_features
        self.aux_task = aux_task
        self.track_key = track_key
        self.mask_key = mask_key

        # Make path relative to this file
        current_file_path = os.path.abspath(__file__)
        parent_directory = os.path.dirname(current_file_path)
        if not os.path.isabs(data_path):
            data_path = os.path.join(parent_directory, "..", "..", data_path)

        print(f"Loading data from {data_path}...")

        keys = ["state", "action", "patch_centers"]
        if use_pi3_features:
            keys.append("pi3_features")
        if aux_task == "track":
            keys += [track_key, mask_key]
        if use_dino_features:
            keys.append("dino_features")

        if os.path.isdir(data_path) and os.path.exists(
                os.path.join(data_path, "episode_ends.npy")):
            # Shared-memory / memmap mode (scripts/export_shm_dataset.py):
            # a directory of raw .npy files, np.load(mmap_mode='r') so ALL
            # concurrent trainings share ONE physical copy (page cache /
            # tmpfs) instead of ~95GB per process
            data_dict = {}
            for k in keys:
                data_dict[k] = np.load(os.path.join(data_path, f"{k}.npy"),
                                       mmap_mode="r")
            episode_ends = np.load(os.path.join(data_path, "episode_ends.npy"))
            self.replay_buffer = ReplayBuffer(
                root={"data": data_dict, "meta": {"episode_ends": episode_ends}})
        elif data_path.endswith(".zarr"):
            # JAMB-style zarr (scripts/convert_tracks_to_zarr.py), loaded
            # exactly like GAPDataset does (full in-memory copy)
            self.replay_buffer = ReplayBuffer.copy_from_path(data_path, keys=keys)
        else:
            # Fallback: flat tracks HDF5 (peilin's generation format)
            data_dict = {}
            with h5py.File(data_path, 'r') as f:
                data_dict["action"] = f["action"][:]
                data_dict["state"] = f["robot_state"][:]
                if use_pi3_features:
                    assert "pi3_feature" in f, (
                        f"use_pi3_features=True but {data_path} has no pi3_feature"
                    )
                    data_dict["pi3_features"] = f["pi3_feature"][:]
                data_dict[track_key] = f[track_key][:]
                data_dict[mask_key] = f[mask_key][:]
                data_dict["patch_centers"] = f["image_patch_centre_3d_position"][:]
                if use_dino_features:
                    assert "dino_features" in f, (
                        f"use_dino_features=True but {data_path} has no dino_features "
                        "(run scripts/add_dinov2_to_tracks.py)"
                    )
                    data_dict["dino_features"] = f["dino_features"][:]
                episode_ends = f["episode_ends"][:]

            root = {
                "data": data_dict,
                "meta": {
                    "episode_ends": episode_ends
                }
            }
            self.replay_buffer = ReplayBuffer(root=root)

        # Create train/val split
        val_mask = get_val_mask(
            n_episodes=self.replay_buffer.n_episodes,
            val_ratio=val_ratio,
            seed=seed
        )
        train_mask = ~val_mask
        train_mask = downsample_mask(
            mask=train_mask,
            max_n=max_train_episodes,
            seed=seed
        )

        # Only 'action' needs the full horizon window. Every other key is
        # consumed at frame 0 only — EXCEPT pi3_features under aux_task=pmp,
        # which also needs the LAST frame (the future-feature target).
        # key_first_k / key_first_last limit per-sample copies accordingly
        # (without this the dataloader starved the GPU at 43 min/epoch).
        single_frame_keys = ["state", "patch_centers"]
        key_first_last = set()
        if aux_task == "track":
            single_frame_keys += [track_key, mask_key]
            if use_pi3_features:
                single_frame_keys.append("pi3_features")
        else:  # pmp
            key_first_last.add("pi3_features")
        if use_dino_features:
            single_frame_keys.append("dino_features")
        key_first_k = {k: 1 for k in single_frame_keys}
        self._key_first_k = key_first_k
        self._key_first_last = key_first_last

        # Create sequence sampler
        self.sampler = SequenceSampler(
            replay_buffer=self.replay_buffer,
            sequence_length=horizon,
            pad_before=pad_before,
            pad_after=pad_after,
            episode_mask=train_mask,
            key_first_k=key_first_k,
            key_first_last=key_first_last,
        )

        self.train_mask = train_mask
        self.horizon = horizon
        self.pad_before = pad_before
        self.pad_after = pad_after

        print(f"Track Dataset initialized:")
        print(f"  Task: {task_name}")
        print(f"  Total episodes: {self.replay_buffer.n_episodes}")
        print(f"  Train episodes: {train_mask.sum()}")
        print(f"  Val episodes: {val_mask.sum()}")
        print(f"  Horizon: {horizon}")
        if use_pi3_features:
            print(f"  Pi3 features shape: {self.replay_buffer['pi3_features'].shape}")
        if aux_task == "track":
            print(f"  3D track shape: {self.replay_buffer[track_key].shape}")
        print(f"  State shape: {self.replay_buffer['state'].shape}")
        print(f"  Action shape: {self.replay_buffer['action'].shape}")

    def get_validation_dataset(self):
        """Create validation dataset with same parameters"""
        val_set = copy.copy(self)
        val_set.sampler = SequenceSampler(
            replay_buffer=self.replay_buffer,
            sequence_length=self.horizon,
            pad_before=self.pad_before,
            pad_after=self.pad_after,
            episode_mask=~self.train_mask,
            key_first_k=self._key_first_k,
            key_first_last=self._key_first_last,
        )
        val_set.train_mask = ~self.train_mask
        return val_set

    def get_normalizer(self, mode="limits", **kwargs):
        """
        Get normalizer for action and agent_pos.
        Pi3 features, tracks, and masks don't need standardization here.
        """
        data = {
            "action": self.replay_buffer["action"],
            "agent_pos": self.replay_buffer["state"],  # State is agent_pos
        }
        normalizer = LinearNormalizer()
        normalizer.fit(data=data, last_n_dims=1, mode=mode, **kwargs)

        if self.use_pi3_features:
            normalizer["pi3_features"] = self._get_identity_normalizer()
        # 3d_track: global ISOTROPIC scale (one std shared across all
        # patches/steps/xyz — per-axis scaling would distort displacement
        # directions). Needed for joint_diffusion, where tracks are a
        # diffusion variable: raw cm-scale displacements would be drowned by
        # the scheduler's unit-variance noise. Harmless when the flag is off
        # (the regression path reads batch["gt_3d_track"] directly).
        normalizer[self.track_key] = self._get_track_normalizer()
        normalizer[self.mask_key] = self._get_identity_normalizer()
        normalizer["patch_centers"] = self._get_identity_normalizer()
        if self.use_dino_features:
            normalizer["dino_features"] = self._get_identity_normalizer()

        return normalizer

    def _get_track_normalizer(self, max_frames=1500):
        """
        Global isotropic scaling for 3d_track: x' = x / rms, where rms is the
        root-mean-square of VALID displacement components over an even sample
        of frames. RMS (zero offset) rather than mean/std keeps the origin
        fixed — a zero displacement stays exactly zero after normalization.
        """
        tracks = self.replay_buffer[self.track_key]        # [T_total, N, H, 3]
        valid = self.replay_buffer[self.mask_key]           # [T_total, N, H]
        T_total = tracks.shape[0]
        idx = np.linspace(0, T_total - 1, min(max_frames, T_total)).astype(int)
        sq_sum, n_elem = 0.0, 0
        for i in idx:
            t = np.asarray(tracks[i], dtype=np.float64)    # [N, H, 3]
            m = np.asarray(valid[i], dtype=bool)            # [N, H]
            if m.any():
                v = t[m]                                    # [n_valid, 3]
                sq_sum += float((v ** 2).sum())
                n_elem += v.size
        rms = float(np.sqrt(sq_sum / max(n_elem, 1)))
        rms = max(rms, 1e-4)  # guard against a degenerate all-static sample
        print(f"[TrackDataset] {self.track_key} global rms = {rms*1000:.2f} mm "
              f"(from {len(idx)} frames, {n_elem} valid components)")

        scale = np.full(3, 1.0 / rms, dtype=np.float32)
        offset = np.zeros(3, dtype=np.float32)
        stat = {
            "min": np.full(3, -rms, dtype=np.float32),
            "max": np.full(3, rms, dtype=np.float32),
            "mean": np.zeros(3, dtype=np.float32),
            "std": np.full(3, rms, dtype=np.float32),
        }
        return SingleFieldLinearNormalizer.create_manual(
            scale=scale, offset=offset, input_stats_dict=stat
        )

    def _get_identity_normalizer(self):
        """
        Identity normalization for pre-extracted features
        """
        # Identity transform: scale=1, offset=0
        scale = np.array([1.0], dtype=np.float32)
        offset = np.array([0.0], dtype=np.float32)

        stat = {
            "min": np.array([0.0], dtype=np.float32),
            "max": np.array([1.0], dtype=np.float32),
            "mean": np.array([0.0], dtype=np.float32),
            "std": np.array([1.0], dtype=np.float32),
        }

        return SingleFieldLinearNormalizer.create_manual(
            scale=scale, offset=offset, input_stats_dict=stat
        )

    def get_all_actions(self) -> torch.Tensor:
        """Return all actions for analysis"""
        return torch.from_numpy(self.replay_buffer["action"])

    def __len__(self) -> int:
        return len(self.sampler)

    def _sample_to_data(self, sample):
        """
        Convert raw sample to data dict
        Args:
            sample: dict with keys 'pi3_features', 'state', 'action', '3d_track', 'track_valid_mask'
        Returns:
            data: dict with structure for training
        """
        # Agent position (state) - only first frame
        agent_pos = sample["state"].astype(np.float32)  # [T, 16]
        agent_pos = agent_pos[0]  # Take first frame: [16]

        # Action sequence (full horizon for training)
        action = sample["action"].astype(np.float32)  # [T, 16]

        obs_dict = {
            "agent_pos": agent_pos,  # [16] - single state
        }

        # Pi3 features (optional — omitted entirely when use_pi3_features=False)
        if self.use_pi3_features:
            pi3_features = sample["pi3_features"].astype(np.float32)
            pi3_features_current = pi3_features[0]  # Take first frame: [num_patches, 1024]

            # We need to reshape pi3_features to match JAMB model expectation (N_views, num_patches, 1024)
            if len(pi3_features_current.shape) == 2:
                pi3_features_current = np.expand_dims(pi3_features_current, axis=0)
            obs_dict["pi3_features"] = pi3_features_current

        # World-frame patch-center positions (4D RoPE coordinates for the
        # visual tokens and track queries) — first frame of the window
        if "patch_centers" in sample:
            obs_dict["patch_centers"] = sample["patch_centers"].astype(np.float32)[0]  # [N, 3]

        if self.use_dino_features and "dino_features" in sample:
            dino = sample["dino_features"].astype(np.float32)[0]  # [1, N, 1024] or [N, 1024]
            if dino.ndim == 2:
                dino = np.expand_dims(dino, axis=0)
            obs_dict["dino_features"] = dino

        data = {
            "obs": obs_dict,
            "action": action,  # [T, 16]
        }

        # 3D Track ground truth (using the first frame in the chunk as the track source)
        if self.aux_task == "track" and self.track_key in sample:
            track = sample[self.track_key].astype(np.float32)
            data["gt_3d_track"] = track[0]  # [N_patches, H_action, 3]

        if self.aux_task == "track" and self.mask_key in sample:
            mask = sample[self.mask_key].astype(bool)
            data["track_valid_mask"] = mask[0]  # [N_patches, H_action]

        # PMP supervision: pi3 features at the LAST frame of the chunk
        if self.aux_task == "pmp":
            fut = sample["pi3_features"].astype(np.float32)[-1]  # [N_views, N, 1024] or [N, 1024]
            if fut.ndim == 2:
                fut = np.expand_dims(fut, axis=0)
            data["future_pi3_features"] = fut

        return data

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Get a sequence sample
        """
        sample = self.sampler.sample_sequence(idx)
        data = self._sample_to_data(sample)
        torch_data = dict_apply(data, torch.from_numpy)
        return torch_data
